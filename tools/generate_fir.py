"""Generate the CY-58 256 x 32 Q15 source-domain Kaiser sinc (stdlib only).

Cutoff is .42 cycles/source frame: 20,160 Hz at 48k, proportionally lower
for upsampling. A literal .45 * target Nyquist would discard the 18k test tone.
32 taps cannot retain 18k within .1 dB AND reject everything above 22.05k by
80 dB; print the measured response rather than claiming that specification.
"""
from pathlib import Path
import argparse
import json
import math

PHASES, TAPS, CUTOFF, BETA = 256, 32, .42, 4.0

def i0(x):
    total = term = 1.0
    for k in range(1, 40):
        term *= x*x/(4*k*k)
        total += term
    return total

def coefficients():
    bank = []
    for p in range(PHASES):
        h = []
        for k in range(TAPS):
            x = k-15-p/PHASES
            w = i0(BETA*math.sqrt(max(0, 1-((k-15.5)/15.5)**2)))/i0(BETA)
            h.append((2*CUTOFF if x == 0 else math.sin(2*math.pi*CUTOFF*x)/(math.pi*x))*w)
        scale = 32768/sum(h)
        exact = [v*scale for v in h]
        q = [math.floor(v) for v in exact]
        order = sorted(range(TAPS), key=lambda k: exact[k]-q[k], reverse=True)
        for k in order[:32768-sum(q)]:
            q[k] += 1
        assert sum(q) == 32768 and min(q) >= -32768 and max(q) <= 32767
        # Includes rounding bias: every MAC prefix is bounded by this L1.
        assert sum(abs(v) for v in q)*32768+16384 < 2**31
        bank.append(q)
    return bank

def response(bank, frequencies):
    lo, hi = float('inf'), 0.
    for f in frequencies:
        cs = [math.cos(2*math.pi*f*k) for k in range(TAPS)]
        sn = [math.sin(2*math.pi*f*k) for k in range(TAPS)]
        for q in bank:
            a = math.hypot(sum(c*v for c,v in zip(cs,q)), sum(s*v for s,v in zip(sn,q)))/32768
            lo, hi = min(lo,a), max(hi,a)
    return [20*math.log10(max(lo,1e-20)),20*math.log10(hi)]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bank = coefficients()
    bound = max(sum(abs(v) for v in q) for q in bank)
    lines = ['// Generated by tools/generate_fir.py; do not edit.', '#pragma once', '#include <stdint.h>',
             '// Kaiser beta=4; cutoff=.42 cycles/input frame; DC sum=32768.',
             '// Max L1=%d; full-scale MAC + rounding <= %d (INT32 safe).'%(bound,bound*32768+16384),
             'static const int16_t firPolyphase[256][32] = {']
    lines += ['  {'+','.join(map(str,q))+'},' for q in bank]
    lines += ['};', 'static_assert(sizeof(firPolyphase)==16384,"flash coefficient budget");']
    data = ('\n'.join(lines)+'\n').encode()
    out = Path(__file__).resolve().parents[1]/'firmware/cydpod_player/app/fir_coefficients.h'
    if args.check:
        assert out.read_text().replace('\r\n','\n') == data.decode(), 'regenerate fir_coefficients.h'
    else:
        out.write_bytes(data)
    print(json.dumps(dict(phases=PHASES,taps=TAPS,bytes=16384,maxL1=bound,
        passband_0_18k_dB=response(bank,[.375*j/256 for j in range(257)]),
        stopband_22050_24000_dB=response(bank,[(22050+1950*j/128)/48000 for j in range(129)]),
        response_1k_10k_18k_dB=[response(bank,[f/48000]) for f in (1000,10000,18000)]),indent=2))

if __name__ == '__main__':
    main()
