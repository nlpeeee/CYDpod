"""CY-51a Q15 polyphase reference; Python stdlib only, deterministic flash tables."""
from pathlib import Path
import math
from math import gcd
out=Path(__file__).resolve().parents[1]/'firmware/cydpod_player/app/fir_coefficients.h'
lines=['// Generated by tools/generate_fir.py; normalized Blackman sinc, Q15.','#pragma once','#include <stdint.h>']
for rate in (48000,32000,24000,22050,16000,12000,11025,8000):
 phases=44100//gcd(rate,44100);cutoff=20800/rate if rate==48000 else .47
 bank=[];maxhalf=0
 for p in range(phases):
  h=[]
  for k in range(128):
   x=k-63.5-p/phases;w=.42-.5*math.cos(2*math.pi*k/127)+.08*math.cos(4*math.pi*k/127)
   h.append((2*cutoff if x==0 else math.sin(2*math.pi*cutoff*x)/(math.pi*x))*w)
  total=sum(h);h=[v/total*32768 for v in h];q=[math.floor(v) for v in h]
  order=sorted(range(128),key=lambda k:h[k]-q[k],reverse=True)
  for k in order[:32768-sum(q)]:q[k]+=1
  assert sum(q)==32768 and min(q)>=-32768 and max(q)<=32767
  maxhalf=max(maxhalf,sum(abs(v) for v in q[:64]),sum(abs(v) for v in q[64:]))
  bank.append('{'+','.join(map(str,q))+'}')
 assert maxhalf*32768<2**31
 lines+=['// rate %d, max half L1 %d, full-scale bound %d'%(rate,maxhalf,maxhalf*32768),
         'static const int16_t fir%d[%d][128]={'%(rate,phases),',\n'.join(bank),'};']
out.write_bytes(('\n'.join(lines)+'\n').encode())
